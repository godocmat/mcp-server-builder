use builder_project::{Assertion, ScenarioV1};
use mcp_policy::{ExecutionLimits, Redactor};
use mcp_runtime::compile_schema;
use mcp_runtime::syntax::is_key;
use serde::Serialize;
use serde_json::{Map, Value};

use super::{json_fits, outcome_for_error};

const MAX_ASSERTIONS: usize = 512;
const MAX_POINTER_BYTES: usize = 2048;

#[derive(Clone, Copy, Debug, Eq, PartialEq, Serialize)]
#[serde(rename_all = "camelCase")]
pub enum RunOutcome {
    Passed,
    AssertionFailed,
    Invalid,
    Denied,
    Failed,
    TimedOut,
    Cancelled,
}

#[derive(Clone, Debug, Eq, PartialEq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct AssertionResult {
    pub index: usize,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub path: Option<String>,
    pub passed: bool,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub code: Option<&'static str>,
}

#[derive(Clone, Debug, Eq, PartialEq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct ScenarioEvaluation {
    pub outcome: RunOutcome,
    pub assertions: Vec<AssertionResult>,
    /// Diagnostic generated by evaluation, if any. The client owns wire diagnostics.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub diagnostic_code: Option<&'static str>,
}

/// Evaluate a saved scenario against the client-normalized result or diagnostic
/// code. Only bounded results reach assertions and only assertion metadata is
/// returned. A missing fixture is a failed run. Cancellation takes precedence.
pub fn evaluate(scenario: &ScenarioV1, response: Result<&Value, &str>) -> ScenarioEvaluation {
    evaluate_with_redactor(scenario, response, &Redactor::default())
}

/// Apply the run's known-secret redactor to assertion evidence.
pub fn evaluate_with_redactor(
    scenario: &ScenarioV1,
    response: Result<&Value, &str>,
    redactor: &Redactor,
) -> ScenarioEvaluation {
    let empty = |outcome, diagnostic_code| ScenarioEvaluation {
        outcome,
        assertions: Vec::new(),
        diagnostic_code,
    };
    if let Err(code @ ("run.cancelled" | "fixture.missing")) = response {
        return empty(outcome_for_error(code), None);
    }
    let sensitive_paths = scenario.sensitive_paths.as_deref().unwrap_or_default();
    if scenario.version != 1
        || scenario.assertions.len() > MAX_ASSERTIONS
        || sensitive_paths.len() > MAX_ASSERTIONS
        || !sensitive_paths.iter().all(|path| valid_pointer(path))
    {
        return empty(RunOutcome::Invalid, Some("scenario.invalid"));
    }
    if response.is_ok_and(|value| !json_fits(value, ExecutionLimits::MAX_OUTPUT_BYTES)) {
        return empty(RunOutcome::Failed, Some("runtime.output_limit"));
    }

    let assertions: Vec<_> = scenario
        .assertions
        .iter()
        .enumerate()
        .map(|(index, assertion)| {
            let path = match assertion {
                Assertion::Equals { path, .. } | Assertion::Schema { path, .. } => Some(path),
                Assertion::ErrorCode { .. } => None,
            };
            let code = check_assertion(assertion, response).err();
            AssertionResult {
                index,
                path: path.and_then(|path| sanitize_path(path, sensitive_paths, redactor)),
                passed: code.is_none(),
                code,
            }
        })
        .collect();

    let expects_error = scenario
        .assertions
        .iter()
        .any(|assertion| matches!(assertion, Assertion::ErrorCode { .. }));
    let (outcome, diagnostic_code) = if assertions
        .iter()
        .any(|assertion| assertion.code == Some("scenario.invalid_assertion"))
    {
        (RunOutcome::Invalid, Some("scenario.invalid"))
    } else if let Err(code) = response
        && !expects_error
    {
        (outcome_for_error(code), None)
    } else if assertions.iter().any(|assertion| !assertion.passed) {
        (
            RunOutcome::AssertionFailed,
            Some("scenario.assertion_failed"),
        )
    } else {
        (RunOutcome::Passed, None)
    };
    ScenarioEvaluation {
        outcome,
        assertions,
        diagnostic_code,
    }
}

fn check_assertion(
    assertion: &Assertion,
    response: Result<&Value, &str>,
) -> Result<(), &'static str> {
    match assertion {
        Assertion::Equals { path, expected } => (value_at(response, path)? == expected)
            .then_some(())
            .ok_or("scenario.value_mismatch"),
        Assertion::Schema { path, schema } => {
            let validator = compile_schema(schema).map_err(|_| "scenario.invalid_assertion")?;
            validator
                .is_valid(value_at(response, path)?)
                .then_some(())
                .ok_or("scenario.schema_mismatch")
        }
        Assertion::ErrorCode { code } => {
            if code.len() > 128 || !code.contains('.') || !code.split('.').all(is_key) {
                return Err("scenario.invalid_assertion");
            }
            (response.err() == Some(code.as_str()))
                .then_some(())
                .ok_or("scenario.error_code_mismatch")
        }
    }
}

fn value_at<'a>(response: Result<&'a Value, &str>, path: &str) -> Result<&'a Value, &'static str> {
    if !valid_pointer(path) {
        return Err("scenario.invalid_assertion");
    }
    response
        .map_err(|_| "scenario.result_required")?
        .pointer(path)
        .ok_or("scenario.path_missing")
}

fn valid_pointer(path: &str) -> bool {
    if path.len() > MAX_POINTER_BYTES
        || (!path.is_empty() && !path.starts_with('/'))
        || path.chars().any(char::is_control)
    {
        return false;
    }
    let mut bytes = path.bytes();
    while let Some(byte) = bytes.next() {
        if byte == b'~' && !matches!(bytes.next(), Some(b'0' | b'1')) {
            return false;
        }
    }
    true
}

fn sanitize_path(path: &str, sensitive_paths: &[String], redactor: &Redactor) -> Option<String> {
    if !valid_pointer(path)
        || sensitive_paths.iter().any(|sensitive| {
            path == sensitive
                || path
                    .strip_prefix(sensitive)
                    .is_some_and(|suffix| suffix.starts_with('/'))
        })
        || redactor.redact_text(path, MAX_POINTER_BYTES).text != path
    {
        return None;
    }
    // Reuse the policy's credential-field rules for decoded pointer components.
    let fields: Map<_, _> = path
        .split('/')
        .skip(1)
        .map(|part| {
            (
                part.replace("~1", "/").replace("~0", "~"),
                Value::Bool(true),
            )
        })
        .collect();
    let segments = Value::Object(fields);
    redactor
        .redact_json(segments.clone(), Redactor::DEFAULT_ENTRY_BYTES)
        .is_ok_and(|safe| safe == segments)
        .then(|| path.to_owned())
}
